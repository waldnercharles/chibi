#!/usr/bin/env python3
"""Bundle Neon Swarm content into fixture.js so the study shows real project data."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PROJECT = ROOT / 'projects' / 'arena2d'
CONTENT = PROJECT / 'content'


def load(path):
    return json.loads(path.read_text())


def pin(p):
    out = {'id': p['id'], 'name': p['name'], 'kind': p['kind'], 'type': p.get('type_name', p['kind'])}
    if p.get('default') is not None:
        out['default'] = p['default']
    binding = p.get('binding')
    if binding and binding.get('kind') == 'component_field':
        out['binding'] = binding['component'].split('.')[-1] + '.' + binding['field']
    return out


def graph(g):
    return {
        'kind': g['kind'],
        'name': g['name'],
        'nodes': [{
            'id': n['id'],
            'type': n['type'],
            'title': n.get('reference_name') or n['type'],
            'x': n['x'],
            'y': n['y'],
            'inputs': [pin(p) for p in n['inputs']],
            'outputs': [pin(p) for p in n['outputs']],
        } for n in g['nodes']],
        'edges': g.get('edges', []),
        'comments': g.get('comment_boxes', []),
    }


def main():
    manifest = load(PROJECT / 'project.json')
    scene = load(CONTENT / manifest['start_scene'])
    fixture = {
        'project': manifest['name'],
        'scenePath': manifest['start_scene'],
        'scene': scene,
        'prototypes': {p.stem: load(p)['components'] for p in sorted((CONTENT / 'prototypes').glob('*.json'))},
        'behaviors': {},
        'assets': sorted(str(p.relative_to(CONTENT)) for p in CONTENT.rglob('*.json')),
    }
    for path in sorted((CONTENT / 'behaviors').glob('*.json')):
        b = load(path)
        fixture['behaviors'][path.stem] = {
            'description': b.get('description', ''),
            'graphs': [graph(g) for g in b['graphs']],
        }
    out = Path(__file__).with_name('fixture.js')
    out.write_text('/* Generated by fixture.py from projects/arena2d. */\nwindow.FIXTURE = '
                   + json.dumps(fixture, separators=(',', ':')) + ';\n')
    print(f'{out} {out.stat().st_size // 1024} KB')


if __name__ == '__main__':
    main()
