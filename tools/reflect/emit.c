#include "reflect_internal.h"

#include <stdlib.h>
#include <string.h>

/* A C string literal, or NULL. */
static void emit_string(FILE *out, const char *text)
{
    if (!text) {
        fputs("NULL", out);
        return;
    }
    fputc('"', out);
    for (const char *c = text; *c; c++) {
        if (*c == '"' || *c == '\\') {
            fputc('\\', out);
        }
        fputc(*c, out);
    }
    fputc('"', out);
}

void emit(FILE *out, const collect_ctx *ctx)
{
    fputs("/* generated reflection pack -- generated by reflect, do not edit. */\n\n", out);
    fputs("#include <stddef.h>\n", out);
    fputs("#include <stdint.h>\n", out);
    for (int i = 0; i < acount(ctx->structs); i++) {
        const char *f = ctx->structs[i].file;
        if (!f || !ends_with(f, ".h")) {
            continue;
        }
        int dup = 0;
        for (int j = 0; j < i; j++) {
            const char *g = ctx->structs[j].file;
            if (g && strcmp(g, f) == 0) {
                dup = 1;
            }
        }
        if (!dup) {
            fprintf(out, "#include \"%s\"\n", f);
        }
    }
    fputs("#include \"support/arena.h\"\n", out);
    fputs("#include \"graph/runtime/eval.h\"\n", out);
    fputs("#include \"graph/model/type.h\"\n", out);
    fputs("#include \"graph/nodes/nodes.h\"\n", out);
    fputs("#include \"graph/runtime/flow.h\"\n", out);
    fputs("#include \"graph/runtime/service.h\"\n", out);
    fputs("#include \"graph/model/registry.h\"\n", out);
    if (acount(ctx->structs)) {
        int has_component = 0;
        for (int i = 0; i < acount(ctx->structs); i++) {
            has_component |= ctx->structs[i].component;
        }
        if (has_component) {
            fputs("#include \"ecs/ecs.h\"\n", out);
            fputs("#include \"graph/runtime/instance.h\"\n", out);
            fputs("#include <string.h>\n", out);
            fputs("#include <assert.h>\n", out);
        }
    }
    fputs("\n", out);

    for (int i = 0; i < acount(ctx->structs); i++) {
        const struct_info *s = &ctx->structs[i];
        fprintf(out, "static const type_field %s_%s_fields[] = {\n", g_prefix, s->name);
        for (int j = 0; j < acount(s->fields); j++) {
            const field_info *f = &s->fields[j];
            fprintf(
                out,
                "    { \"%s\", %s, offsetof(%s, %s), sizeof(%s), \"%s\", ",
                f->name,
                f->pin,
                s->name,
                f->name,
                f->spelling,
                field_type_name(f)
            );
            emit_string(out, f->description);
            fputs(" },\n", out);
        }
        fputs("};\n\n", out);

        fprintf(out, "const type_desc %s_T_%s = {\n", g_prefix, s->name);
        fprintf(out, "    .name = \"%s\",\n", s->name);
        fprintf(out, "    .size = sizeof(%s),\n", s->name);
        fprintf(out, "    .fields = %s_%s_fields,\n", g_prefix, s->name);
        fprintf(out, "    .field_count = %d,\n", acount(s->fields));
        if (s->alias_of) {
            fprintf(out, "    .alias_of = \"%s\",\n", s->alias_of);
        }
        fputs("};\n\n", out);
    }

    fprintf(out, "const type_desc *const %s_REGISTRY_TYPES[] = {\n", g_prefix);
    for (int i = 0; i < acount(ctx->structs); i++) {
        fprintf(out, "    &%s_T_%s,\n", g_prefix, ctx->structs[i].name);
    }
    fputs("};\n", out);
    fprintf(out, "const int %s_REGISTRY_TYPE_COUNT = %d;\n\n", g_prefix, acount(ctx->structs));

    for (int i = 0; i < acount(ctx->enums); i++) {
        const enum_info *enumeration = &ctx->enums[i];
        fprintf(
            out,
            "static const enum_value_desc %s_ENUM_%s_VALUES[] = {\n",
            g_prefix,
            enumeration->name
        );
        for (int j = 0; j < acount(enumeration->values); j++) {
            const enum_value_info *value = &enumeration->values[j];
            fprintf(
                out,
                "    { %d, \"%s\", \"%s\" },\n",
                value->value,
                value->name,
                value->label
            );
        }
        fprintf(out, "};\n");
        fprintf(
            out,
            "static const enum_desc %s_ENUM_%s = {\n"
            "    .name = \"%s\",\n"
            "    .values = %s_ENUM_%s_VALUES,\n"
            "    .value_count = %d,\n"
            "};\n\n",
            g_prefix,
            enumeration->name,
            enumeration->name,
            g_prefix,
            enumeration->name,
            acount(enumeration->values)
        );
    }
    if (acount(ctx->enums)) {
        fprintf(out, "const enum_desc *const %s_REGISTRY_ENUMS[] = {\n", g_prefix);
        for (int i = 0; i < acount(ctx->enums); i++) {
            fprintf(out, "    &%s_ENUM_%s,\n", g_prefix, ctx->enums[i].name);
        }
        fputs("};\n", out);
    } else {
        fprintf(out, "const enum_desc *const %s_REGISTRY_ENUMS[1] = { NULL };\n", g_prefix);
    }
    fprintf(out, "const int %s_REGISTRY_ENUM_COUNT = %d;\n\n", g_prefix, acount(ctx->enums));

    int component_count = 0;
    for (int i = 0; i < acount(ctx->structs); i++) {
        if (ctx->structs[i].component) {
            emit_component_accessors(out, &ctx->structs[i]);
            component_count++;
        }
    }
    if (component_count) {
        fprintf(out, "const ecs_component_desc *const %s_REGISTRY_COMPONENTS[] = {\n", g_prefix);
        for (int i = 0; i < acount(ctx->structs); i++) {
            if (ctx->structs[i].component) {
                fprintf(
                    out,
                    "    &%s_COMPONENT_%s,\n",
                    g_prefix,
                    ctx->structs[i].name
                );
            }
        }
        fputs("};\n", out);
    } else {
        fprintf(out, "const void *const %s_REGISTRY_COMPONENTS[1] = { NULL };\n", g_prefix);
    }
    fprintf(out, "const int %s_REGISTRY_COMPONENT_COUNT = %d;\n\n", g_prefix, component_count);

    int service_count = 0;
    for (int i = 0; i < acount(ctx->fns); i++) {
        for (int j = 0; j < acount(ctx->fns[i].pname); j++) {
            if (ctx->fns[i].pservice[j] && ctx->fns[i].pservice_type[j]) {
                int seen = 0;
                for (int k = 0; k < i; k++) {
                    for (int l = 0; l < acount(ctx->fns[k].pname); l++) {
                        seen |= ctx->fns[k].pservice[l] &&
                                strcmp(ctx->fns[k].pservice_type[l], ctx->fns[i].pservice_type[j]) ==
                                    0;
                    }
                }
                for (int l = 0; l < j; l++) {
                    seen |= ctx->fns[i].pservice[l] &&
                            strcmp(ctx->fns[i].pservice_type[l], ctx->fns[i].pservice_type[j]) ==
                                0;
                }
                if (!seen) {
                    fprintf(
                        out,
                        "static const service_desc %s_SERVICE_%d = { \"%s\", "
                        "UINT64_C(%llu) };\n",
                        g_prefix,
                        service_count,
                        ctx->fns[i].pservice_type[j],
                        (unsigned long long)stable_service_id(ctx->fns[i].pservice_type[j])
                    );
                    service_count++;
                }
            }
        }
    }
    fprintf(out, "const service_desc *const %s_REGISTRY_SERVICES[] = {\n", g_prefix);
    for (int i = 0; i < service_count; i++) {
        fprintf(out, "    &%s_SERVICE_%d,\n", g_prefix, i);
    }
    fputs("};\n", out);
    fprintf(out, "const int %s_REGISTRY_SERVICE_COUNT = %d;\n\n", g_prefix, service_count);

    /* native prototypes, so wrappers can call the annotated functions */
    for (int i = 0; i < acount(ctx->fns); i++) {
        const fn_info *f = &ctx->fns[i];
        fprintf(out, "%s %s(", f->ret, f->name);
        for (int j = 0; j < acount(f->pname); j++) {
            fprintf(out, "%s%s %s", j ? ", " : "", f->ptype[j], f->pname[j]);
        }
        fputs(");\n", out);
    }
    if (acount(ctx->fns)) {
        fputc('\n', out);
    }

    for (int i = 0; i < acount(ctx->fns); i++) {
        if (ctx->fns[i].read) {
            emit_read_fn(out, &ctx->fns[i]);
        } else if (ctx->fns[i].exec) {
            emit_exec_fn(out, &ctx->fns[i]);
        } else {
            emit_fn(out, &ctx->fns[i]);
        }
    }

    for (int i = 0; i < acount(ctx->structs); i++) {
        emit_struct_nodes(out, &ctx->structs[i]);
    }
    for (int i = 0; i < acount(ctx->fns); i++) {
        if (ctx->fns[i].read) {
            emit_read_node(out, &ctx->fns[i]);
        } else if (ctx->fns[i].exec) {
            emit_exec_node(out, &ctx->fns[i]);
        } else {
            emit_fn_node(out, &ctx->fns[i]);
        }
    }
    for (int i = 0; i < acount(ctx->structs); i++) {
        if (ctx->structs[i].component) {
            emit_component_unwrap(out, &ctx->structs[i]);
            emit_component_nodes(out, &ctx->structs[i]);
            emit_component_nodes_desc(out, &ctx->structs[i]);
            emit_component_entity_nodes(out, &ctx->structs[i]);
            emit_component_entity_nodes_desc(out, &ctx->structs[i]);
            emit_component_field_nodes(out, &ctx->structs[i]);
        }
    }

    fprintf(out, "node_desc *const %s_REGISTRY_NODES[] = {\n", g_prefix);
    for (int i = 0; i < acount(ctx->structs); i++) {
        fprintf(out, "    &%s_NODE_Make_%s,\n", g_prefix, ctx->structs[i].name);
        fprintf(out, "    &%s_NODE_Break_%s,\n", g_prefix, ctx->structs[i].name);
    }
    for (int i = 0; i < acount(ctx->fns); i++) {
        fprintf(out, "    &%s_NODE_%s,\n", g_prefix, ctx->fns[i].name);
    }
    for (int i = 0; i < acount(ctx->structs); i++) {
        if (!ctx->structs[i].component) {
            continue;
        }
        fprintf(
            out,
            "    &%s_NODE_Get_%s, &%s_NODE_Set_%s, &%s_NODE_Has_%s,\n",
            g_prefix,
            ctx->structs[i].name,
            g_prefix,
            ctx->structs[i].name,
            g_prefix,
            ctx->structs[i].name
        );
        fprintf(
            out,
            "    &%s_NODE_GetEntity_%s, &%s_NODE_SetEntity_%s, "
            "&%s_NODE_HasEntity_%s,\n",
            g_prefix,
            ctx->structs[i].name,
            g_prefix,
            ctx->structs[i].name,
            g_prefix,
            ctx->structs[i].name
        );
        fprintf(
            out,
            "    &%s_NODE_Add_%s, &%s_NODE_Remove_%s,\n",
            g_prefix,
            ctx->structs[i].name,
            g_prefix,
            ctx->structs[i].name
        );
        for (int j = 0; j < acount(ctx->structs[i].fields); j++) {
            const field_info *field = &ctx->structs[i].fields[j];
            if (component_field_settable(field)) {
                fprintf(
                    out,
                    "    &%s_NODE_Set_%s_%s,\n",
                    g_prefix,
                    ctx->structs[i].name,
                    field->name
                );
            }
        }
    }
    for (int i = 0; i < acount(ctx->structs); i++) {
        if (component_unwrap(&ctx->structs[i])) {
            fprintf(out, "    &%s_NODE_Unwrap_%s,\n", g_prefix, ctx->structs[i].name);
        }
    }
    fputs("};\n", out);
    int component_node_count = component_count * 8;
    for (int i = 0; i < acount(ctx->structs); i++) {
        component_node_count += component_unwrap(&ctx->structs[i]);
        if (ctx->structs[i].component) {
            for (int j = 0; j < acount(ctx->structs[i].fields); j++) {
                component_node_count += component_field_settable(
                    &ctx->structs[i].fields[j]
                );
            }
        }
    }
    int node_count = acount(ctx->structs) * 2 + acount(ctx->fns) + component_node_count;
    fprintf(out, "const int %s_REGISTRY_NODE_COUNT = %d;\n", g_prefix, node_count);
    fprintf(out, "const registry_pack %s_REGISTRY_PACK = {\n", g_prefix);
    fprintf(out, "    .name = \"%s\",\n", g_prefix);
    fprintf(out, "    .nodes = %s_REGISTRY_NODES,\n", g_prefix);
    fprintf(out, "    .node_count = %d,\n", node_count);
    fprintf(out, "    .types = %s_REGISTRY_TYPES,\n", g_prefix);
    fprintf(out, "    .type_count = %d,\n", acount(ctx->structs));
    fprintf(out, "    .services = %s_REGISTRY_SERVICES,\n", g_prefix);
    fprintf(out, "    .service_count = %d,\n", service_count);
    fprintf(out, "    .enums = %s_REGISTRY_ENUMS,\n", g_prefix);
    fprintf(out, "    .enum_count = %d,\n", acount(ctx->enums));
    fputs("};\n", out);
}
